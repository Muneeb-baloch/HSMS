import { body, param, query, ValidationChain } from 'express-validator';

export const validateChat = (): ValidationChain[] => [
  body('agentType')
    .trim()
    .notEmpty()
    .withMessage('Agent type is required')
    .isIn(['resident-assistant', 'committee-advisor', 'financial-analyst', 'compliance-monitor'])
    .withMessage('Invalid agent type'),

  body('message')
    .trim()
    .notEmpty()
    .withMessage('Message is required')
    .isLength({ min: 1, max: 5000 })
    .withMessage('Message must be between 1 and 5000 characters'),

  body('conversationId')
    .optional()
    .isMongoId()
    .withMessage('Invalid conversation ID'),

  body('societyId')
    .trim()
    .notEmpty()
    .withMessage('Society ID is required')
    .isMongoId()
    .withMessage('Invalid Society ID'),
];

