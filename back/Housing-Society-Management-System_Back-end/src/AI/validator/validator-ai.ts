export const validateCreateInsight = (): ValidationChain[] => [
  body('societyId')
    .trim()
    .notEmpty()
    .withMessage('Society ID is required')
    .isMongoId()
    .withMessage('Invalid Society ID'),

  body('insightType')
    .trim()
    .notEmpty()
    .withMessage('Insight type is required')
    .isIn(['prediction', 'anomaly', 'recommendation', 'trend', 'alert'])
    .withMessage('Invalid insight type'),

  body('category')
    .trim()
    .notEmpty()
    .withMessage('Category is required')
    .isIn(['financial', 'complaints', 'members', 'maintenance', 'compliance', 'general'])
    .withMessage('Invalid category'),

  body('title')
    .trim()
    .notEmpty()
    .withMessage('Title is required')
    .isLength({ min: 3, max: 200 })
    .withMessage('Title must be between 3 and 200 characters'),

  body('description')
    .trim()
    .notEmpty()
    .withMessage('Description is required')
    .isLength({ min: 10, max: 5000 })
    .withMessage('Description must be between 10 and 5000 characters'),

  body('severity')
    .optional()
    .isIn(['info', 'low', 'medium', 'high', 'critical'])
    .withMessage('Invalid severity'),

  body('data')
    .optional()
    .isObject()
    .withMessage('Data must be an object'),

  body('actionable')
    .optional()
    .isBoolean()
    .withMessage('Actionable must be a boolean'),

  body('actionUrl')
    .optional()
    .isString()
    .trim()
    .withMessage('Action URL must be a string'),

  body('expiresAt')
    .optional()
    .isISO8601()
    .withMessage('Invalid expiry date format')
    .toDate(),

  body('generatedBy')
    .optional()
    .isString()
    .trim()
    .withMessage('Generated by must be a string'),
];

